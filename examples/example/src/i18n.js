export function applyLandingStaticTranslations(locale) {
  if (typeof document === 'undefined') return;
  const code = resolveExampleLocale(locale);
  const d = getExampleDictionary(code);
  document.documentElement.setAttribute('lang', code);
  document.documentElement.setAttribute('dir', getLocaleDirection(code));

  const setText = (sel, text) => {
    const el = document.querySelector(sel);
    if (el && typeof text === 'string') el.textContent = text;
  };
  const setFirstTextNode = (el, text) => {
    if (!el || typeof text !== 'string') return;
    const textNode = [...el.childNodes].find((n) => n.nodeType === 3);
    if (textNode) textNode.textContent = text;
  };
  const renderHtmlLines = (el, html, allowEm) => {
    if (!el || typeof html !== 'string') return;
    const doc = el.ownerDocument;
    while (el.firstChild) el.removeChild(el.firstChild);
    const lines = html.split('<br />');
    lines.forEach((line, idx) => {
      if (idx > 0) el.appendChild(doc.createElement('br'));
      if (allowEm) {
        const emMatch = /^([\s\S]*?)<em>([\s\S]*?)<\/em>([\s\S]*)$/.exec(line);
        if (emMatch) {
          if (emMatch[1]) el.appendChild(doc.createTextNode(emMatch[1]));
          const em = doc.createElement('em');
          em.textContent = emMatch[2];
          el.appendChild(em);
          if (emMatch[3]) el.appendChild(doc.createTextNode(emMatch[3]));
          return;
        }
      }
      el.appendChild(doc.createTextNode(line.replace(/<[^>]+>/g, '')));
    });
  };

  setText('.skip-link', d.skipToContent);
  setText('.product-nav a[href="./"]', d.navProduct);
  setText('.product-nav a[href="./#features"]', d.navFeatures);
  setText('.product-nav a[href="./#integration"]', d.navDocs);
  setText('.product-nav a[href="../"]', d.navExamples);
  setFirstTextNode(document.querySelector('.product-start'), `${d.navGetStarted} `);
  renderHtmlLines(document.querySelector('.hero-copy h1'), d.heroTitleHtml, true);
  setText('.hero-description', d.heroDesc);
  setFirstTextNode(document.querySelector('.hero-copy .actions a.button'), `${d.heroTryBtn} `);
  setText('.hero-copy .actions a.text-link', d.heroGithubLink);
  setText('#try .eyebrow', d.tryEyebrow);
  renderHtmlLines(document.querySelector('#try h2'), d.tryTitleHtml, false);
  setText('#try > .try-layout > div > p:not(.eyebrow):not(.section-note)', d.tryDesc);
  setText('#try [data-pwa-install]', d.tryInstallBtn);
  setText('#try [data-pwa-diagnostics]', d.tryDiagnosticsBtn);
  setText('#try .text-link', d.tryWorkspaceLink);
  const panelHeader = document.querySelector('.live-panel-header');
  if (panelHeader) {
    const titleNode = [...panelHeader.childNodes].find((n) => n.nodeType === 3 && n.textContent.trim());
    if (titleNode) titleNode.textContent = `${d.liveSnapshotTitle}\n              `;
  }
  setText('#live-project-label', d.liveProjectLabel);
  setText('#live-connectivity-label', d.liveConnectivityLabel);
  setText('#live-notices-label', d.liveNoticesLabel);
  setText('#live-theme-label', d.liveThemeLabel);
  setText('#demo-theme option[value="light"]', d.tsModes?.light?.label);
  setText('#demo-theme option[value="dark"]', d.tsModes?.dark?.label);
  setText('#demo-theme option[value="auto"]', d.tsModes?.auto?.label);
  const demoLangSelect = document.getElementById('demo-language');
  if (demoLangSelect) demoLangSelect.setAttribute('aria-label', d.languageLabel);
  const copyInstallBtn = document.querySelector('[data-copy-install]');
  if (copyInstallBtn && !copyInstallBtn.hidden && d.copy) {
    copyInstallBtn.textContent = d.copy;
  }
  document.querySelectorAll('.copy-code').forEach((btn) => {
    if (d.copy) btn.textContent = d.copy;
    if (d.copyCodeAria) btn.setAttribute('aria-label', d.copyCodeAria);
  });
}

let _syncingExampleLocale = false;
export function syncExampleLocale(requestedLocale, assistantInstance) {
  if (_syncingExampleLocale) return;
  _syncingExampleLocale = true;
  try {
    const raw = requestedLocale || 'auto';
    if (assistantInstance && typeof assistantInstance.setLocale === 'function') {
      assistantInstance.setLocale(raw);
    }
    const pwa = typeof window !== 'undefined' && (window.YouGePWA || window.PWA);
    if (pwa && typeof pwa.setLanguage === 'function') {
      pwa.setLanguage(raw);
    }
    if (pwa && typeof pwa.configureInstallExperience === 'function') {
      pwa.configureInstallExperience({ locale: raw });
    }
  } finally {
    _syncingExampleLocale = false;
  }
}
