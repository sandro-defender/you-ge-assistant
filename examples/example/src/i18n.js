export { DEFAULT_LOCALE, SUPPORTED_LOCALES, LOCALE_METADATA, resolveLocale, isRtlLocale };

export function resolveExampleLocale(candidate) {
  if (candidate && candidate !== 'auto') {
    const resolved = resolveLocale({ explicit: candidate, navigator: null });
    return SUPPORTED_LOCALES.includes(resolved) ? resolved : DEFAULT_LOCALE;
  }
  const navLang =
    typeof navigator !== 'undefined'
      ? ((Array.isArray(navigator.languages) && navigator.languages[0]) || navigator.language || '')
      : '';
  const docLang = typeof document !== 'undefined' ? (document.documentElement?.lang || '') : '';
  const detected = navLang || docLang;
  if (!detected) return DEFAULT_LOCALE;
  const resolved = resolveLocale({ navigatorLanguage: detected, navigator: null });
  return SUPPORTED_LOCALES.includes(resolved) ? resolved : DEFAULT_LOCALE;
}

export function getLocaleDirection(locale) {
  return isRtlLocale(resolveExampleLocale(locale)) ? 'rtl' : 'ltr';
}

export function buildLocaleOptions(locale) {
  const autoLabels = {
    en: 'Auto (browser)',
    ka: 'ავტო (ბრაუზერი)',
    ru: 'Авто (браузер)',
    fr: 'Auto (navigateur)',
    it: 'Auto (browser)',
    de: 'Auto (Browser)',
    sv: 'Auto (webbläsare)',
    nl: 'Auto (browser)',
    no: 'Auto (nettleser)',
    da: 'Auto (browser)',
    et: 'Automaatne (brauser)',
    es: 'Auto (navegador)',
  };
  const active = resolveExampleLocale(locale);
  const autoLabel = autoLabels[active] || autoLabels.en;
  return [
    { value: 'auto', label: autoLabel },
    ...SUPPORTED_LOCALES.map((code) => ({
      value: code,
      label: LOCALE_METADATA[code]?.nativeName || code,
    })),
  ];
}

